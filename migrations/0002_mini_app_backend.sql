CREATE TABLE IF NOT EXISTS chat_runtime (
    chat_id BIGINT PRIMARY KEY REFERENCES chat_settings(chat_id) ON DELETE CASCADE,
    bot_present BOOLEAN NOT NULL DEFAULT FALSE,
    bot_admin BOOLEAN NOT NULL DEFAULT FALSE,
    can_delete_messages BOOLEAN NOT NULL DEFAULT FALSE,
    can_restrict_members BOOLEAN NOT NULL DEFAULT FALSE,
    can_ban_members BOOLEAN NOT NULL DEFAULT FALSE,
    last_update_at TIMESTAMPTZ,
    last_permission_check_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS protection_modules (
    chat_id BIGINT NOT NULL REFERENCES chat_settings(chat_id) ON DELETE CASCADE,
    module_key TEXT NOT NULL,
    title TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    healthy BOOLEAN NOT NULL DEFAULT TRUE,
    configured BOOLEAN NOT NULL DEFAULT FALSE,
    last_triggered_at TIMESTAMPTZ,
    config JSONB NOT NULL DEFAULT '{}'::JSONB,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (chat_id, module_key)
);

CREATE TABLE IF NOT EXISTS moderation_incidents (
    id BIGSERIAL PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES chat_settings(chat_id) ON DELETE CASCADE,
    incident_type TEXT NOT NULL,
    severity TEXT NOT NULL DEFAULT 'medium'
        CHECK (severity IN ('low', 'medium', 'high', 'critical')),
    detected_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    acknowledged_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    resolved_by BIGINT,
    status TEXT NOT NULL DEFAULT 'detected'
        CHECK (status IN ('detected', 'acknowledged', 'resolved')),
    metadata JSONB NOT NULL DEFAULT '{}'::JSONB
);
CREATE INDEX IF NOT EXISTS idx_incidents_chat_status
    ON moderation_incidents(chat_id, status, detected_at DESC);

