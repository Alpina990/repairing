UPDATE protection_modules AS module SET
    enabled=CASE module.module_key
        WHEN 'anti_flood' THEN settings.flood_limit > 0
        WHEN 'welcome' THEN settings.welcome_enabled
        WHEN 'rules' THEN trim(settings.rules) <> ''
        WHEN 'blocklist' THEN EXISTS(
            SELECT 1 FROM blocked_terms term WHERE term.chat_id=settings.chat_id)
        ELSE module.enabled END,
    configured=CASE module.module_key
        WHEN 'anti_flood' THEN TRUE
        WHEN 'warning_policy' THEN TRUE
        WHEN 'welcome' THEN trim(settings.welcome_template) <> ''
        WHEN 'rules' THEN trim(settings.rules) <> ''
        WHEN 'blocklist' THEN EXISTS(
            SELECT 1 FROM blocked_terms term WHERE term.chat_id=settings.chat_id)
        ELSE module.configured END,
    config=CASE module.module_key
        WHEN 'anti_flood' THEN jsonb_build_object(
            'limit',settings.flood_limit,'window_secs',settings.flood_window_secs,
            'action',settings.flood_action)
        WHEN 'warning_policy' THEN jsonb_build_object(
            'limit',settings.warn_limit,'action',settings.warn_action,
            'mute_duration_secs',settings.mute_duration_secs)
        WHEN 'welcome' THEN jsonb_build_object('template',settings.welcome_template)
        WHEN 'rules' THEN jsonb_build_object('rules',settings.rules)
        ELSE module.config END,
    updated_at=NOW()
FROM chat_settings AS settings
WHERE module.chat_id=settings.chat_id
  AND module.module_key IN ('anti_flood','warning_policy','welcome','rules','blocklist');
