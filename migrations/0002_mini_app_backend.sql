CREATE TABLE IF NOT EXISTS managed_chats (
    chat_id BIGINT PRIMARY KEY REFERENCES chat_settings(chat_id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    username TEXT,
    chat_type TEXT NOT NULL CHECK (chat_type IN ('group', 'supergroup')),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chat_members (
    chat_id BIGINT NOT NULL REFERENCES chat_settings(chat_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL,
    username TEXT,
    first_name TEXT NOT NULL,
    last_name TEXT,
    is_bot BOOLEAN NOT NULL DEFAULT FALSE,
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'member'
        CHECK (status IN ('creator', 'administrator', 'member', 'restricted', 'left', 'kicked')),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (chat_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_chat_members_username
    ON chat_members(chat_id, lower(username)) WHERE username IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_chat_members_name
    ON chat_members(chat_id, lower(first_name), lower(last_name));
CREATE INDEX IF NOT EXISTS idx_chat_members_last_seen
    ON chat_members(chat_id, last_seen_at DESC);

